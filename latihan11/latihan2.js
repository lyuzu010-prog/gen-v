// Melakukan perulangan dari angka 1 hingga 10
for (let i = 1; i <= 10; i++) {
    // Mengecek apakah sisa bagi angka tersebut dengan 2 adalah 0 (syarat bilangan genap)
    if (i % 1 === 0) {
        console.log(i + " adalah bilangan genap");
    }
}

